// slider
const slidesEl = document.querySelector('.slides');
const dotsEl = document.getElementById('dots');
const shots = [...document.querySelectorAll('.shot')];
shots.forEach((_,i)=>{
  const b=document.createElement('button');
  b.setAttribute('aria-label','Go to slide '+(i+1));
  if(i===0) b.classList.add('active');
  b.addEventListener('click',()=>{
    slidesEl.scrollTo({left: shots[i].offsetLeft - 16, behavior:'smooth'});
  });
  dotsEl.appendChild(b);
});
function updateDots(){
  const idx = Math.round(slidesEl.scrollLeft / 256);
  [...dotsEl.children].forEach((d,i)=>d.classList.toggle('active', i===idx));
}
slidesEl.addEventListener('scroll', updateDots, {passive:true});
document.getElementById('prevBtn').addEventListener('click', ()=>slidesEl.scrollBy({left:-260, behavior:'smooth'}));
document.getElementById('nextBtn').addEventListener('click', ()=>slidesEl.scrollBy({left:260, behavior:'smooth'}));

// reveal on scroll
const io = new IntersectionObserver((entries)=>{
  entries.forEach(e=>{ if(e.isIntersecting){ e.target.classList.add('visible'); io.unobserve(e.target);} });
},{threshold:.12});
document.querySelectorAll('.reveal').forEach(el=>io.observe(el));

