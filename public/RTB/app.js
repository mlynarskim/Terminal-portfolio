let currentLang = localStorage.getItem('rtb-lang') || ((navigator.language || 'pl').toLowerCase().startsWith('pl') ? 'pl' : 'pl');

function setLang(lang){
  currentLang = lang;
  localStorage.setItem('rtb-lang', lang);
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    if(i18n[lang] && i18n[lang][key]){
      el.textContent = i18n[lang][key];
    }
  });
  document.querySelectorAll('.store-badge').forEach(badge=>{
    const img = badge.querySelector('img');
    if(img){
      img.src = badge.getAttribute('data-badge-' + lang);
      img.alt = lang === 'pl' ? (img.src.includes('apple') ? 'Pobierz z App Store' : 'Pobierz z Google Play') : (img.src.includes('apple') ? 'Download on the App Store' : 'Get it on Google Play');
    }
  });
  document.getElementById('btnPL').classList.toggle('active', lang==='pl');
  document.getElementById('btnEN').classList.toggle('active', lang==='en');
  document.title = lang==='pl'
    ? 'Rate That Beach — Znajdź najlepsze plaże w pobliżu'
    : 'Rate That Beach — Find the best beaches nearby';
}

document.getElementById('btnPL').addEventListener('click', ()=>setLang('pl'));
document.getElementById('btnEN').addEventListener('click', ()=>setLang('en'));

// burger
const burger = document.getElementById('burger');
